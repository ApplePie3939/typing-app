import type { Difficulty, PromptUnit, TypingPrompt } from './types.ts';

function normalizeReading(reading: string): string {
  return reading.replace(/[A-Z]/g, (ch) => ch.toLowerCase());
}

function prompt(
  id: string,
  difficulty: Difficulty,
  senderName: string,
  senderRole: string,
  channel: string,
  incomingMessage: string,
  units: [string, string][],
): TypingPrompt {
  const parsed: PromptUnit[] = units.map(([display, reading]) => ({
    display,
    reading: normalizeReading(reading),
  }));
  return {
    id,
    difficulty,
    senderName,
    senderRole,
    channel,
    incomingMessage,
    replyText: parsed.map((u) => u.display).join(''),
    replyReading: parsed.map((u) => u.reading).join(''),
    units: parsed,
  };
}

